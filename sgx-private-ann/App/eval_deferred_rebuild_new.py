def _parse_kv_line(kv_text: str) -> Dict:
    out: Dict[str, object] = {}
    for token in kv_text.strip().split():
        if "=" not in token:
            continue
        k, v = token.split("=", 1)
        # Preserve complex list-like fields as strings for now.
        if "," in v or ":" in v:
            out[k] = v
            continue
        try:
            out[k] = int(v)
            continue
        except ValueError:
            pass
        try:
            out[k] = float(v)
            continue
        except ValueError:
            pass
        out[k] = v
    return out

