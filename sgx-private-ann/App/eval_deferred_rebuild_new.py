@dataclass
class CachedNodePy:
    node_id: int
    max_level: int
    vector: np.ndarray
    neighbors_by_slot: List[List[int]]

class ClientUpperLayersIndexPy:
    def __init__(self, path: Path):
        hdr_dt = client_header_dtype()
        h = np.fromfile(path, dtype=hdr_dt, count=1)
        if h.size != 1:
            raise ValueError(f"could not read client cache header from {path}")
        h0 = h[0]
        self.num_cached_nodes = int(h0["num_cached_nodes"])
        self.dim = int(h0["dim"])
        self.M = int(h0["M"])
        self.upper_start_layer = int(h0["upper_start_layer"])
        self.upper_layer_count = int(h0["upper_layer_count"])
        self.record_bytes = int(h0["record_bytes"])
        self.invalid_node_id = int(h0["invalid_node_id"])
        rec_dt = client_record_dtype(self.dim, self.upper_layer_count, self.M)
        records = np.memmap(path, dtype=rec_dt, mode="r", offset=hdr_dt.itemsize, shape=(self.num_cached_nodes,))
        self.nodes: Dict[int, CachedNodePy] = {}
        for rec in records:
            node_id = int(rec["node_id"])
            vec = np.asarray(rec["vector"], dtype=np.float32).copy()
            neighbors_by_slot: List[List[int]] = []
            for slot in range(self.upper_layer_count):
                deg = int(rec["upper_degrees"][slot])
                nbrs = [int(x) for x in rec["upper_neighbors"][slot][:deg] if int(x) != self.invalid_node_id]
                neighbors_by_slot.append(nbrs)
            self.nodes[node_id] = CachedNodePy(
                node_id=node_id,
                max_level=int(rec["max_level"]),
                vector=vec,
                neighbors_by_slot=neighbors_by_slot,
            )

    def l2(self, q: np.ndarray, x: np.ndarray) -> float:
        d = q - x
        return float(np.dot(d, d))

    def greedy_one_cached_layer(self, q: np.ndarray, entry: int, slot: int) -> int:
        if entry not in self.nodes:
            return int(entry)
        cur = int(entry)
        cur_dist = self.l2(q, self.nodes[cur].vector)
        changed = True
        while changed:
            changed = False
            if cur not in self.nodes:
                break
            for nb in self.nodes[cur].neighbors_by_slot[slot]:
                if nb not in self.nodes:
                    continue
                d = self.l2(q, self.nodes[nb].vector)
                if d < cur_dist:
                    cur = nb
                    cur_dist = d
                    changed = True
        return cur

    def search_cached_upper_layers(self, q: np.ndarray, full_entrypoint: int) -> int:
        ep = int(full_entrypoint)
        for slot in range(self.upper_layer_count - 1, -1, -1):
            ep = self.greedy_one_cached_layer(q, ep, slot)
        return ep

def l2_distance(q: np.ndarray, x: np.ndarray) -> float:
    d = q - x
    return float(np.dot(d, d))

@dataclass
class PlainLayerNode:
    node_id: int
    vector: np.ndarray | None
    neighbors: np.ndarray
    is_dummy: bool

@dataclass
class PlainCandidate:
    node_id: int
    node: PlainLayerNode
    dist: float

def read_plain_layer_node(
    index: ServerIndexView,
    layer: int,
    key_global_id: int,
    visited: set[int],
) -> Tuple[PlainLayerNode, bool]:
    """
    Python mirror of enclave read_layer_node(layer, global_id, qid).

    SGX layer-access semantics:
      - layer lookup is keyed by global id.
      - invalid/missing ids return dummy with isVisited=True.
      - visited metadata is query-local and keyed by global id only.
      - a successful read marks the global id visited for the rest of the query.

    This mirror is used to compare traversal correctness against the enclave
    LayerORAM interface.
    """
    if key_global_id == INVALID_NODE_ID or not index.exists_in_server_layer(int(key_global_id), layer):
        m_layer = 2 * index.M if layer == 0 else index.M
        dummy = PlainLayerNode(
            node_id=INVALID_NODE_ID,
            vector=None,
            neighbors=np.full((m_layer,), INVALID_NODE_ID, dtype=np.uint32),
            is_dummy=True,
        )
        return dummy, True

    node_id = int(key_global_id)
    is_visited = node_id in visited
    visited.add(node_id)

    node = PlainLayerNode(
        node_id=node_id,
        vector=index.vector(node_id),
        neighbors=index.layer_neighbors_fixed(node_id, layer),
        is_dummy=False,
    )
    return node, is_visited

def plain_node_distance(q: np.ndarray, node: PlainLayerNode) -> float:
    if node.is_dummy or node.vector is None:
        return DUMMY_DISTANCE
    return l2_distance(q, node.vector)

def plaintext_fixedstep_layer_with_visited(
    index: ServerIndexView,
    q: np.ndarray,
    layer: int,
    ep: int,
    T: int,
    w: int,
    visited: set[int],
):
    """
    Python mirror of enclave fixed_step_layer_search(layer, q, ep, T, w, qid).

    It is used for both:
      - server layer 1: final C[0] becomes ep0 for layer 0
      - server layer 0: raw W becomes the returned candidate set

    Strict current pseudocode semantics:
      - C is not padded with dummy candidates.
      - invalid neighbor slots are still appended into E with DUMMY_DISTANCE.
      - next C is the first min(w, len(E)) entries after sorting.
    """
    W_ids: List[int] = []
    W_dists: List[float] = []
    C: List[PlainCandidate] = []

    per_step_E_sizes: List[int] = []
    per_step_E_unique_sizes: List[int] = []
    per_step_C_real_sizes: List[int] = []
    per_step_new_visited_sizes: List[int] = []
    per_step_skipped_visited_sizes: List[int] = []
    per_step_dummy_suppressed_sizes: List[int] = []

    if ep == INVALID_NODE_ID or w == 0:
        stats = {
            "per_step_E_sizes": [0] * T,
            "per_step_E_unique_sizes": [0] * T,
            "per_step_C_real_sizes": [0] * T,
            "per_step_new_visited_sizes": [0] * T,
            "per_step_skipped_visited_sizes": [0] * T,
            "per_step_dummy_suppressed_sizes": [0] * T,
            "W_size": 0,
            "unique_nodes_visited": len(visited),
            "unique_nodes_in_W": 0,
        }
        return W_ids, W_dists, C, stats

    ep_node, _ep_visited = read_plain_layer_node(index, layer, int(ep), visited)
    if ep_node.is_dummy:
        stats = {
            "per_step_E_sizes": [0] * T,
            "per_step_E_unique_sizes": [0] * T,
            "per_step_C_real_sizes": [0] * T,
            "per_step_new_visited_sizes": [0] * T,
            "per_step_skipped_visited_sizes": [0] * T,
            "per_step_dummy_suppressed_sizes": [0] * T,
            "W_size": 0,
            "unique_nodes_visited": len(visited),
            "unique_nodes_in_W": 0,
        }
        return W_ids, W_dists, C, stats

    ep_dist = plain_node_distance(q, ep_node)
    ep_cand = PlainCandidate(int(ep), ep_node, ep_dist)
    C = [ep_cand]
    W_ids.append(ep_cand.node_id)
    W_dists.append(ep_cand.dist)

    for _ in range(T):
        E: List[PlainCandidate] = []
        new_visited = 0
        skipped_visited = 0
        dummy_suppressed = 0

        for c in C:
            # Defensive only; in the strict no-padding version C should contain real candidates.
            if c.node_id == INVALID_NODE_ID or c.node.is_dummy:
                continue

            for nb in c.node.neighbors:
                nb_i = int(nb)
                nb_node, is_visited = read_plain_layer_node(index, layer, nb_i, visited)

                d_real = plain_node_distance(q, nb_node)
                suppress = bool(is_visited) or bool(nb_node.is_dummy)
                dist = DUMMY_DISTANCE if suppress else d_real

                if nb_node.is_dummy:
                    dummy_suppressed += 1
                elif is_visited:
                    skipped_visited += 1
                else:
                    new_visited += 1

                E.append(PlainCandidate(nb_i, nb_node, dist))

        per_step_E_sizes.append(len(E))
        per_step_E_unique_sizes.append(len(set(c.node_id for c in E)))
        per_step_new_visited_sizes.append(new_visited)
        per_step_skipped_visited_sizes.append(skipped_visited)
        per_step_dummy_suppressed_sizes.append(dummy_suppressed)

        E.sort(key=lambda c: (c.dist, c.node_id))
        take = min(w, len(E))
        C = E[:take]

        per_step_C_real_sizes.append(
            sum(1 for c in C if c.node_id != INVALID_NODE_ID and not c.node.is_dummy and c.dist < DUMMY_DISTANCE * 0.5)
        )

        for c in C:
            W_ids.append(c.node_id)
            W_dists.append(c.dist)

    stats = {
        "per_step_E_sizes": per_step_E_sizes,
        "per_step_E_unique_sizes": per_step_E_unique_sizes,
        "per_step_C_real_sizes": per_step_C_real_sizes,
        "per_step_new_visited_sizes": per_step_new_visited_sizes,
        "per_step_skipped_visited_sizes": per_step_skipped_visited_sizes,
        "per_step_dummy_suppressed_sizes": per_step_dummy_suppressed_sizes,
        "W_size": len(W_ids),
        "unique_nodes_visited": len(visited),
        "unique_nodes_in_W": len(set(x for x in W_ids if x != INVALID_NODE_ID)),
    }
    return W_ids, W_dists, C, stats

def plaintext_fixedstep_with_visited(index: ServerIndexView, q: np.ndarray, ep: int, T0: int, T1: int, w: int, topk: int):
    """
    Plaintext mirror of the current SGX ORAM-frame algorithm:

      1. Run fixed-step search on server layer 1.
      2. Take layer1 final frontier C[0] as ep0.
      3. Run fixed-step search on server layer 0 from ep0.
      4. Sort/dedup/take topK from layer0 raw W.

    Visited semantics are PER LAYER.

    This matches the current "one ORAM per server layer" design:
      - LayerORAM_1 stores its own last_qid metadata.
      - LayerORAM_0 stores its own last_qid metadata.
      - Visiting global id x in layer 1 does not mark x visited in layer 0.
    """
    import time
    t0 = time.perf_counter()

    visited_l1: set[int] = set()
    visited_l0: set[int] = set()

    _l1_W_ids, _l1_W_dists, l1_C, l1_stats = plaintext_fixedstep_layer_with_visited(
        index, q, layer=1, ep=int(ep), T=T1, w=w, visited=visited_l1
    )

    ep0 = int(ep)
    if l1_C and l1_C[0].node_id != INVALID_NODE_ID and not l1_C[0].node.is_dummy:
        ep0 = int(l1_C[0].node_id)

    l0_W_ids, l0_W_dists, _l0_C, l0_stats = plaintext_fixedstep_layer_with_visited(
        index, q, layer=0, ep=ep0, T=T0, w=w, visited=visited_l0
    )

    out_ids, out_dists = sort_dedup_take_topk(l0_W_ids, l0_W_dists, topk)
    t1 = time.perf_counter()

    stats = dict(l0_stats)
    stats["layer1_W_size"] = l1_stats["W_size"]
    stats["layer1_final_C_size"] = len(l1_C)
    stats["layer1_ep0"] = ep0
    stats["layer1_unique_nodes_visited"] = len(visited_l1)
    stats["layer0_unique_nodes_visited"] = len(visited_l0)
    stats["layer1_per_step_E_sizes"] = l1_stats["per_step_E_sizes"]
    stats["layer1_per_step_E_unique_sizes"] = l1_stats["per_step_E_unique_sizes"]
    stats["layer1_per_step_C_real_sizes"] = l1_stats["per_step_C_real_sizes"]
    stats["layer1_per_step_new_visited_sizes"] = l1_stats["per_step_new_visited_sizes"]
    stats["layer1_per_step_skipped_visited_sizes"] = l1_stats["per_step_skipped_visited_sizes"]

    # Keep this legacy aggregate field for the existing result JSON schema.
    # It now means total unique visited node entries across per-layer ORAMs.
    # A global id visited in both layer 1 and layer 0 is counted twice because
    # it lives in two different LayerORAM instances.
    stats["unique_nodes_visited"] = len(visited_l1) + len(visited_l0)

    return out_ids, out_dists, (t1 - t0) * 1000.0, stats

def sort_dedup_take_topk(raw_ids: List[int], raw_dists: List[float], topk: int) -> Tuple[List[int], List[float]]:
    pairs = [
        (int(i), float(d))
        for i, d in zip(raw_ids, raw_dists)
        if int(i) != INVALID_NODE_ID and np.isfinite(d) and float(d) < DUMMY_DISTANCE * 0.5
    ]
    pairs.sort(key=lambda x: (x[1], x[0]))
    out_ids: List[int] = []
    out_dists: List[float] = []
    seen = set()
    for i, d in pairs:
        if i in seen:
            continue
        seen.add(i)
        out_ids.append(i)
        out_dists.append(d)
        if len(out_ids) >= topk:
            break
    return out_ids, out_dists

def _avg_int_list(list_of_lists: List[List[int]], T: int) -> List[float]:
    if not list_of_lists:
        return [0.0] * T
    return [float(np.mean([xs[i] for xs in list_of_lists])) for i in range(T)]


def parse_result_line(line: str) -> Dict:
    m = RESULT_RE.match(line.strip())
    if not m:
        raise ValueError(f"failed to parse RESULT line: {line}")
    ids = [int(x) for x in m.group("ids").split(",") if x != ""]
    dists = [float(x) for x in m.group("dists").split(",") if x != ""]
    maintenance_ms = float(m.group("maint")) if m.group("maint") is not None else 0.0
    total_with_maintenance_ms = (
        float(m.group("total_maint")) if m.group("total_maint") is not None
        else float(m.group("lat")) + maintenance_ms
    )
    return {
        "q": int(m.group("q")),
        "latency_ms": float(m.group("lat")),
        "online_latency_ms": float(m.group("lat")),
        "upper_ms": float(m.group("upper")),
        "ecall_ms": float(m.group("ecall")),
        "decrypt_ms": float(m.group("dec")),
        "maintenance_ms": maintenance_ms,
        "total_with_maintenance_ms": total_with_maintenance_ms,
        "entrypoint_l1": int(m.group("ep")),
        "ids": ids,
        "dists": dists,
    }

