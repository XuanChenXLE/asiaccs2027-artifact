def summarize_sgx_query_only(
    sgx_results: List[Dict],
    sgx_summary_including_init: Dict,
    latency_skip_first: int = 1,
) -> Dict:
    """
    Summarize SGX results with query-only latency by default.

    The current enclave may build the initial ORAM hierarchy inside q=0's
    search ECALL. Therefore q=0 latency can include one-time ORAM init/build
    cost. We exclude q=0 from the main latency summary, but correctness still
    uses all queries. The original app SUMMARY is kept in "including_init".
    """
    if not sgx_results:
        return dict(sgx_summary_including_init)

    latency_rows = sgx_results[latency_skip_first:]
    if not latency_rows:
        latency_rows = sgx_results

    lat = np.asarray([float(r.get("latency_ms", 0.0)) for r in latency_rows], dtype=np.float64)
    upper = np.asarray([float(r.get("upper_ms", 0.0)) for r in latency_rows], dtype=np.float64)
    ecall = np.asarray([float(r.get("ecall_ms", 0.0)) for r in latency_rows], dtype=np.float64)
    dec = np.asarray([float(r.get("decrypt_ms", 0.0)) for r in latency_rows], dtype=np.float64)
    maint = np.asarray([float(r.get("maintenance_ms", 0.0)) for r in latency_rows], dtype=np.float64)
    total_maint = np.asarray([float(r.get("total_with_maintenance_ms", float(r.get("latency_ms", 0.0)))) for r in latency_rows], dtype=np.float64)

    out = {
        "num_queries": len(sgx_results),
        "latency_summary_queries": int(len(latency_rows)),
        "latency_skip_first": int(latency_skip_first),
        "latency_note": (
            "Main latency fields exclude the first RESULT row by default. "
            "This avoids counting one-time ORAM initial build in q=0 as "
            "steady-state query latency. Recall/MRR still use all queries."
        ),
        "avg_latency_ms": float(np.mean(lat)) if lat.size else 0.0,
        "avg_online_latency_ms": float(np.mean(lat)) if lat.size else 0.0,
        "avg_maintenance_ms": float(np.mean(maint)) if maint.size else 0.0,
        "avg_total_with_maintenance_ms": float(np.mean(total_maint)) if total_maint.size else 0.0,
        "avg_upper_ms": float(np.mean(upper)) if upper.size else 0.0,
        "avg_ecall_ms": float(np.mean(ecall)) if ecall.size else 0.0,
        "avg_decrypt_ms": float(np.mean(dec)) if dec.size else 0.0,
        "p50_latency_ms": float(np.percentile(lat, 50)) if lat.size else 0.0,
        "p95_latency_ms": float(np.percentile(lat, 95)) if lat.size else 0.0,
        "p99_latency_ms": float(np.percentile(lat, 99)) if lat.size else 0.0,
        "p50_maintenance_ms": float(np.percentile(maint, 50)) if maint.size else 0.0,
        "p95_maintenance_ms": float(np.percentile(maint, 95)) if maint.size else 0.0,
        "p99_maintenance_ms": float(np.percentile(maint, 99)) if maint.size else 0.0,
        "p50_total_with_maintenance_ms": float(np.percentile(total_maint, 50)) if total_maint.size else 0.0,
        "p95_total_with_maintenance_ms": float(np.percentile(total_maint, 95)) if total_maint.size else 0.0,
        "p99_total_with_maintenance_ms": float(np.percentile(total_maint, 99)) if total_maint.size else 0.0,
        "including_init": {
            "num_queries": sgx_summary_including_init.get("num_queries"),
            "avg_latency_ms": sgx_summary_including_init.get("avg_latency_ms"),
            "avg_upper_ms": sgx_summary_including_init.get("avg_upper_ms"),
            "avg_ecall_ms": sgx_summary_including_init.get("avg_ecall_ms"),
            "avg_decrypt_ms": sgx_summary_including_init.get("avg_decrypt_ms"),
            "avg_maintenance_ms": sgx_summary_including_init.get("avg_maintenance_ms", 0.0),
            "avg_total_with_maintenance_ms": sgx_summary_including_init.get("avg_total_with_maintenance_ms", sgx_summary_including_init.get("avg_latency_ms")),
            "p50_latency_ms": sgx_summary_including_init.get("p50_latency_ms"),
            "p95_latency_ms": sgx_summary_including_init.get("p95_latency_ms"),
            "p99_latency_ms": sgx_summary_including_init.get("p99_latency_ms"),
        },
    }
    return out


