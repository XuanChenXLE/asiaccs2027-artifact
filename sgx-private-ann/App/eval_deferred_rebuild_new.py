def read_fvecs(path: Path, limit: int | None = None) -> np.ndarray:
    with path.open("rb") as f:
      dim = np.fromfile(f, dtype=np.int32, count=1)
      if dim.size == 0:
          raise ValueError(f"empty fvecs file: {path}")
      d = int(dim[0])
      f.seek(0, os.SEEK_END)
      size = f.tell()
      stride = 4 + 4 * d
      if size % stride != 0:
          raise ValueError(f"invalid fvecs size for {path}")
      n = size // stride
      if limit is not None:
          n = min(n, limit)
      f.seek(0)
      raw = np.fromfile(f, dtype=np.float32, count=n * (d + 1)).reshape(n, d + 1)
    dims = raw[:, 0].view(np.int32)
    if not np.all(dims == d):
        raise ValueError(f"inconsistent fvecs dims in {path}")
    return np.ascontiguousarray(raw[:, 1:])

def read_ivecs(path: Path) -> np.ndarray:
    with path.open("rb") as f:
      dim = np.fromfile(f, dtype=np.int32, count=1)
      if dim.size == 0:
          raise ValueError(f"empty ivecs file: {path}")
      d = int(dim[0])
      f.seek(0, os.SEEK_END)
      size = f.tell()
      stride = 4 + 4 * d
      if size % stride != 0:
          raise ValueError(f"invalid ivecs size for {path}")
      n = size // stride
      f.seek(0)
      raw = np.fromfile(f, dtype=np.int32, count=n * (d + 1)).reshape(n, d + 1)
    if not np.all(raw[:, 0] == d):
        raise ValueError(f"inconsistent ivecs dims in {path}")
    return np.ascontiguousarray(raw[:, 1:])

def maybe_run_build(build_cmd: str, cwd: Path | None) -> None:
    if not build_cmd:
        return
