def recall_at_k(pred: List[int], gt: np.ndarray, k: int) -> float:
    gt_set = set(int(x) for x in gt[:k].tolist())
    hit = sum(1 for x in pred[:k] if int(x) in gt_set)
    return hit / float(k)

def mrr_at_k(pred: List[int], gt: np.ndarray, k: int) -> float:
    gt_set = set(int(x) for x in gt[:k].tolist())
    for rank, docid in enumerate(pred[:k], start=1):
        if int(docid) in gt_set:
            return 1.0 / float(rank)
    return 0.0

def topk_overlap(a: List[int], b: List[int], k: int) -> float:
    return len(set(a[:k]) & set(b[:k])) / float(k)

def file_size_mb(path: Path) -> float:
    if path.is_dir():
        total = 0
        for p in path.rglob("*"):
            if p.is_file():
                total += p.stat().st_size
        return total / (1024.0 * 1024.0)
    return path.stat().st_size / (1024.0 * 1024.0)

