class ServerIndexView:
    def __init__(self, path: Path):
        hdr_dt = server_header_dtype()
        h = np.fromfile(path, dtype=hdr_dt, count=1)
        if h.size != 1:
            raise ValueError(f"could not read header from {path}")
        h0 = h[0]
        self.N = int(h0["N"])
        self.dim = int(h0["dim"])
        self.M = int(h0["M"])
        self.entrypoint = int(h0["entrypoint"])
        rec_dt = server_record_dtype(self.dim, self.M)
        self.records = np.memmap(path, dtype=rec_dt, mode="r", offset=hdr_dt.itemsize, shape=(self.N,))

    def vector(self, node_id: int) -> np.ndarray:
        return np.asarray(self.records[node_id]["vector"], dtype=np.float32)

    def max_level_of(self, node_id: int) -> int:
        return int(self.records[node_id]["max_level"])

    def exists_in_server_layer(self, node_id: int, layer: int) -> bool:
        if node_id == INVALID_NODE_ID or node_id < 0 or node_id >= self.N:
            return False
        if layer == 0:
            return True
        if layer == 1:
            # Match split_server_index.py: layer 1 includes nodes with max_level >= 1.
            # The l1_degree fallback protects against exporter inconsistencies.
            return self.max_level_of(node_id) >= 1 or int(self.records[node_id]["l1_degree"]) > 0
        return self.max_level_of(node_id) >= layer

    def layer_neighbors_fixed(self, node_id: int, layer: int) -> np.ndarray:
        # Match layer{i}_nodes.bin semantics: every record stores one fixed-size
        # neighbor list for that layer, including INVALID_NODE_ID padding.
        if layer == 0:
            return np.asarray(self.records[node_id]["l0_neighbors"], dtype=np.uint32)
        if layer == 1:
            return np.asarray(self.records[node_id]["l1_neighbors"], dtype=np.uint32)
        raise ValueError(f"unsupported server layer for plaintext baseline: {layer}")

    def l0_neighbors(self, node_id: int) -> np.ndarray:
        deg = int(self.records[node_id]["l0_degree"])
        return np.asarray(self.records[node_id]["l0_neighbors"][:deg], dtype=np.uint32)

    def l1_neighbors(self, node_id: int) -> np.ndarray:
        deg = int(self.records[node_id]["l1_degree"])
        return np.asarray(self.records[node_id]["l1_neighbors"][:deg], dtype=np.uint32)

