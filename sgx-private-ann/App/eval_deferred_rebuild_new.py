def ensure_encrypted(server_index: Path, encrypted_server_index: Path, force: bool) -> None:
    if encrypted_server_index.exists() and not force:
        log(f"encrypted file already exists, reuse: {encrypted_server_index}")
        return
    key = bytes.fromhex(DEMO_AES_KEY_HEX)
    plain = server_index.read_bytes()
    aesgcm = AESGCM(key)
    iv = os.urandom(AES_GCM_IV_BYTES)
    ct_and_tag = aesgcm.encrypt(iv, plain, None)
    ciphertext, tag = ct_and_tag[:-AES_GCM_TAG_BYTES], ct_and_tag[-AES_GCM_TAG_BYTES:]
    blob = CIPHER_BLOB_HEADER_STRUCT.pack(iv, tag, len(ciphertext)) + ciphertext
    encrypted_server_index.parent.mkdir(parents=True, exist_ok=True)
    encrypted_server_index.write_bytes(blob)
    log(f"wrote encrypted index: {encrypted_server_index}")

